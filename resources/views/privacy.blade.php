        cross-service advertising.
    </p>

    <h2>7. Artificial intelligence processing</h2>
    <p>
        Projector uses artificial intelligence as part of its core features, including:
    </p>
    <ul>
        <li>Turning meeting notes, transcripts, and uploaded documents into summaries, action items, tasks, and other project documents</li>
        <li>Identifying the type of an imported document or spreadsheet and extracting tasks from it</li>
        <li>Creating searchable embeddings (numeric representations) of document content</li>
        <li>Interpreting plain-English report requests, such as those made through the Slack integration</li>
        <li>Checking whether a project description gives enough context, and suggesting improvements</li>
        <li>Transcribing uploaded or recorded meeting audio</li>
    </ul>
    <p>
        To provide these features, the service sends uploaded files, document content, and text entered by
        users to an AI provider for processing. By default this is OpenAI. An organization's administrators may
        instead use their own OpenAI or Google Gemini account, or a self-hosted model that the organization runs
        itself. When an organization uses its own account, that provider's terms with the organization apply. Meeting audio is sent to AssemblyAI for transcription.
    </p>
    <p>
        Some processing runs automatically, such as generating action items when meeting notes are added and
        creating embeddings when a document is saved. Other processing runs when a user asks for it. The
        documents the AI produces are shown to users in Projector, and users can review and edit them.
    </p>
    <p>
        AI-generated documents and embeddings are stored in Projector as part of the project they belong to
        until they or the project are deleted. Custom prompts that users save for reuse are stored until they
        are deleted. One-time instructions typed for a single AI run are not saved. The service logs the amount
        of AI usage for billing, but not the content sent or returned. Meeting recordings that have not been
        approved are deleted after 10 days.
    </p>
    <p>
        The operator states that information submitted to the AI features is not used to train AI models, by
        the operator or by the AI providers under the terms that apply to the service. People working for
        the operator or an AI provider may review prompts, submitted content, or outputs.
    </p>
    <p>
        The public demo gives anyone a temporary account, without signing up, with sample projects to try the
        AI features on. Content in a demo account, including anything a visitor adds, is processed by the AI
        providers described above like any other account's, and the demo account and everything in it is
        deleted after 24 hours. Visitors should not put confidential information into the demo.
    </p>
    <p>
        By creating an account, users agree to the AI processing described in this section.
    </p>
    <p>
        The operator states that AI is not used to make decisions that produce legal or similarly significant
        effects on people.
    </p>
    <p>
        Choices about the AI features: AI processing cannot be turned off, but an organization's administrators
        can choose which AI provider is used, including a self-hosted model, and can turn off individual
        transformations. Questions and privacy requests about information processed by the AI features can be
        sent to <a href="mailto:privacy@kaufmaninternational.com">privacy@kaufmaninternational.com</a>.
    </p>

    <h2>8. Google account connection</h2>
    <p>
        Projector optionally lets you connect your own Google account to export task reports
        directly to Google Sheets and Google Docs in your own Google Drive.
    </p>
    <p>This feature requests exactly one Google OAuth scope:</p>
    <p class="scope">https://www.googleapis.com/auth/drive.file</p>
    <p>This scope only grants Projector access to files that Projector itself creates. It does not grant:</p>
    <ul>
        <li>Access to any existing files already in your Google Drive</li>
        <li>Access to files created by any other application</li>
        <li>Any access to Gmail, Calendar, Contacts, or any other Google service</li>
    </ul>
    <p>
        When you click an export button, Projector uses this connection to create a new Google
        Sheet or Google Doc containing the task report you requested, and writes that report's
        data into it. That file is created directly in your own Google Drive &mdash; Projector does
        not retain a copy of the exported file's contents after creating it.
    </p>
    <p>
        Projector stores your Google access and refresh tokens, encrypted at rest, solely to
        maintain this connection between export requests. You can revoke this connection at any
        time from <strong>Settings &gt; Integrations</strong> within Projector, which deletes the
        stored tokens immediately. You can also revoke access directly from your
        <a href="https://myaccount.google.com/permissions" target="_blank" rel="noopener">Google Account permissions page</a>.
    </p>

